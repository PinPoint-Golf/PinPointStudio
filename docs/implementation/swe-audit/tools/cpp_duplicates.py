#!/usr/bin/env python3
"""Copied C++ (and QML) in scope.   cpp_duplicates.py <repo-root>

The gui-catalogue's method (tools/find_duplicates.py) applied to C++: comments and string contents blanked,
numbers -> N, identifiers kept. Two signals:
  1. block clones -- maximal runs of >= MINRUN identical normalised non-trivial lines in two places
     (different files, or far apart in one file)
  2. file pairs  -- Jaccard / containment of 5-token shingles (whole-file likeness)
Clones are textual: same-job-different-code is for the reviewers to find.
"""
import os, re, sys, json, collections, itertools
sys.path.insert(0, os.path.dirname(__file__))
from common import *

root = sys.argv[1]
MINRUN = 8
files = walk(root, SCOPE + BOUNDARY, CPP_EXT) + walk(root, SCOPE, (".qml",))
TRIV = re.compile(r"^(?:[{}()\[\];,]+|#include.*|#pragma.*|namespace.*|public:|private:|protected:|signals:|return;|break;|continue;|else|\}\s*else\s*\{|default:|case N:)$")
def norm(l):
    l = l.strip()
    l = re.sub(r"\b\d+(?:\.\d+)?[fFuUlL]*\b", "N", l)
    return re.sub(r"\s+", " ", l)
docs = {}
for f in files:
    lines = strip_comments(read(root, f)).splitlines()
    docs[f] = [(i + 1, norm(l)) for i, l in enumerate(lines) if norm(l) and not TRIV.match(norm(l))]

index = collections.defaultdict(list)
for f, L in docs.items():
    for k in range(len(L) - MINRUN + 1):
        key = "\n".join(x[1] for x in L[k:k + MINRUN])
        if len(key) < 160: continue                       # short lines -> boilerplate
        index[key].append((f, k))
pairs = collections.defaultdict(set)
for key, occ in index.items():
    if len(occ) < 2 or len(occ) > 8: continue
    for (fa, ka), (fb, kb) in itertools.combinations(sorted(occ), 2):
        if fa == fb and abs(ka - kb) < MINRUN * 3: continue
        pairs[(fa, fb, ka - kb)].add(ka)
clones = []
for (fa, fb, delta), starts in pairs.items():
    starts = sorted(starts); run = [starts[0]]
    for s in starts[1:] + [None]:
        if s is not None and s == run[-1] + 1: run.append(s); continue
        ka = run[0]; kb = ka - delta; length = len(run) + MINRUN - 1
        la = docs[fa][ka][0]; lb = docs[fb][kb][0]
        clones.append(dict(a=f"{fa}:{la}", b=f"{fb}:{lb}", lines=length,
                           sample=[x[1] for x in docs[fa][ka:ka + min(length, 6)]]))
        if s is not None: run = [s]
clones.sort(key=lambda c: -c["lines"])

def sh(L, k=5):
    toks = re.findall(r"[A-Za-z_]\w*|[{}()\[\]:;,.=+\-*/<>!?&|]", " ".join(x[1] for x in L))
    return set(zip(*[toks[i:] for i in range(k)])) if len(toks) >= k else set()
S = {f: sh(L) for f, L in docs.items() if len(L) >= 30}
inv = collections.defaultdict(list)
for f, s in S.items():
    for t in s: inv[t].append(f)
cand = collections.Counter()
for t, fs in inv.items():
    if 2 <= len(fs) <= 10:
        for a, b in itertools.combinations(sorted(fs), 2): cand[(a, b)] += 1
fp = []
for (a, b), n in cand.items():
    if n < 60: continue
    inter = len(S[a] & S[b]); j = inter / len(S[a] | S[b]); c = inter / min(len(S[a]), len(S[b]))
    if j >= 0.25 or c >= 0.45: fp.append(dict(a=a, b=b, jaccard=round(j, 2), containment=round(c, 2)))
fp.sort(key=lambda x: -x["containment"])
json.dump(dict(clones=clones[:500], file_pairs=fp), open(out_path(root, "cpp_duplicates.json"), "w"), indent=1)
cross = [c for c in clones if c["a"].rsplit(":", 1)[0] != c["b"].rsplit(":", 1)[0]]
same = collections.Counter(c["a"].rsplit(":", 1)[0] for c in clones if c not in cross)
L = ["# Copied code (generated by tools/cpp_duplicates.py — do not edit)", "",
     f"Block clones of ≥ {MINRUN} normalised non-trivial lines: {len(clones)} kept (cap 500); {len(cross)} between different files.", "",
     "## Within one file (count of clone pairs)", "", "| file | pairs |", "|---|---|"] + [f"| {f} | {n} |" for f, n in same.most_common(15)] + [
     "", "## Between files (largest first, top 100)", "",
     "| lines | first | second | starts with |", "|---|---|---|---|"]
for c in cross[:100]:
    L.append(f"| {c['lines']} | {c['a']} | {c['b']} | `{c['sample'][0][:70].replace('|', '/')}` |")
L += ["", f"## File pairs that are largely the same ({len(fp)})", "", "| a | b | jaccard | containment |", "|---|---|---|---|"]
for p in fp[:60]: L.append(f"| {p['a']} | {p['b']} | {p['jaccard']} | {p['containment']} |")
open(out_path(root, "cpp_duplicates.md"), "w").write("\n".join(L) + "\n")
print("clones", len(clones), "file pairs", len(fp))
