#!/usr/bin/env python3
"""The C++ <-> QML seam and object ownership.   seam_inventory.py <repo-root>

  - context properties set in main.cpp (app-lifetime globals), with the C++ type of each
  - C++ types registered for QML and every place QML instantiates one (a view owning a model)
  - Q_INVOKABLE / Q_PROPERTY returning QVariantMap / QVariantList (stringly-typed contracts)
  - `mutable` members, QThread / moveToThread / QtConcurrent sites (state and concurrency)
"""
import os, re, sys, json, collections
sys.path.insert(0, os.path.dirname(__file__))
from common import *

root = sys.argv[1]
main = read(root, "src/Gui/main.cpp")
ctx = []
for m in re.finditer(r'setContextProperty\(\s*QStringLiteral\("(\w+)"\)\s*,\s*&?(\w+)', main):
    name, var = m.group(1), m.group(2)
    t = re.search(r"^\s*([\w:<>]+)\s+" + re.escape(var) + r"\s*[\(\{;]", main, re.M)
    ctx.append(dict(name=name, var=var, type=t.group(1) if t else "?", line=main[:m.start()].count("\n") + 1))

all_cpp = walk(root, ["src"], CPP_EXT)
registered = {}
for f in all_cpp:
    src = read(root, f)
    for m in re.finditer(r"class\s+(\w+)\s*(?:final\s*)?:\s*public\s+[\w:]+[^{]*\{(.{0,600})", src, re.S):
        if "QML_ELEMENT" in m.group(2) or "QML_NAMED_ELEMENT" in m.group(2):
            registered[m.group(1)] = f
    for m in re.finditer(r"qmlRegister\w*<(\w+)>", src):
        registered.setdefault(m.group(1), f)

qml_all = walk(root, ["src/Gui"], QML_EXT)
inst = collections.defaultdict(list)
for f in qml_all:
    src = read(root, f)
    for t in registered:
        for m in re.finditer(r"(?m)^\s*" + t + r"\s*\{", src):
            inst[t].append(f"{f}:{src[:m.start()].count(chr(10)) + 2}")

scope_h = [f for f in walk(root, SCOPE + BOUNDARY, (".h",))]
variant, mutables, threads = [], [], []
for f in walk(root, SCOPE + BOUNDARY, CPP_EXT):
    src = strip_comments(read(root, f))
    for ln, line in enumerate(src.splitlines(), 1):
        if re.search(r"Q_INVOKABLE\s+(?:virtual\s+)?QVariant(Map|List)\b", line) or re.search(r"Q_PROPERTY\(\s*QVariant(Map|List)\b", line):
            variant.append(f"{f}:{ln}: {line.strip()[:140]}")
        if re.search(r"\bmutable\b(?!\s*->)", line) and not re.search(r"\]\s*\(.*\)\s*mutable", line):
            mutables.append(f"{f}:{ln}: {line.strip()[:120]}")
        if re.search(r"\b(QThread|moveToThread|QtConcurrent::run|QThreadPool|std::thread)\b", line):
            threads.append(f"{f}:{ln}: {line.strip()[:120]}")

per_file_variant = collections.Counter(v.split(":")[0] for v in variant)
json.dump(dict(context_properties=ctx, registered_types=registered, qml_instantiations=inst,
               variant_contracts=variant, mutable_members=mutables, thread_sites=threads),
          open(out_path(root, "seam_inventory.json"), "w"), indent=1)
L = ["# C++ ↔ QML seam and ownership (generated by tools/seam_inventory.py — do not edit)", "",
     f"## Context properties: {len(ctx)} app-lifetime globals (src/Gui/main.cpp)", "", "| name | C++ type | main.cpp line |", "|---|---|---|"]
for c in ctx: L.append(f"| `{c['name']}` | {c['type']} | {c['line']} |")
L += ["", f"## C++ types QML instantiates ({sum(len(v) for v in inst.values())} instantiations of {len(inst)} types) — each is an object whose owner is a view", "",
      "| type | declared in | instantiated at |", "|---|---|---|"]
for t, where in sorted(inst.items(), key=lambda x: -len(x[1])):
    L.append(f"| `{t}` | {registered[t]} | " + "<br>".join(where[:8]) + (f"<br>… +{len(where)-8}" if len(where) > 8 else "") + " |")
L += ["", f"## QVariantMap / QVariantList contracts: {len(variant)} (per file)", "", "| file | count |", "|---|---|"]
for f, n in per_file_variant.most_common(): L.append(f"| {f} | {n} |")
L += ["", f"## `mutable` members: {len(mutables)}", ""] + [f"- {m}" for m in mutables[:80]]
L += ["", f"## Thread sites: {len(threads)}", ""] + [f"- {t}" for t in threads[:80]]
open(out_path(root, "seam_inventory.md"), "w").write("\n".join(L) + "\n")
print("ctx", len(ctx), "registered", len(registered), "instantiated types", len(inst), "variant", len(variant), "mutable", len(mutables), "threads", len(threads))
