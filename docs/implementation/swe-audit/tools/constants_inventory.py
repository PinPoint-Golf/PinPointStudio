#!/usr/bin/env python3
"""Named constants and repeated magic numbers.   constants_inventory.py <repo-root>

  - every `constexpr`/`const` scalar k-constant in scope, grouped by NAME defined in more than one file
  - distinctive literal values (not 0/1/2/0.5/…) that back differently-named constants in different files
  - distinctive decimal literals written inline (outside a constant definition) in 3+ files of ring 1
"""
import os, re, sys, json, collections
sys.path.insert(0, os.path.dirname(__file__))
from common import *

root = sys.argv[1]
files = walk(root, SCOPE + BOUNDARY, CPP_EXT)
DEF = re.compile(r"(?:static\s+)?(?:inline\s+)?(?:constexpr|const)\s+(?:static\s+)?(double|float|int|qreal|qint64|int64_t|std::size_t|size_t|unsigned)\s+(k\w+)\s*=\s*([^;]+);")
TRIVIAL = {"0", "1", "2", "3", "4", "5", "10", "100", "1000", "0.0", "1.0", "2.0", "0.5", "-1", "0.25", "0.75", "180.0", "360.0", "90.0", "60.0", "1e-9", "1e-6", "1e-12"}
by_name = collections.defaultdict(list); by_value = collections.defaultdict(list)
inline_lit = collections.defaultdict(set)
for f in files:
    src = strip_comments(read(root, f))
    for m in DEF.finditer(src):
        ln = src[:m.start()].count("\n") + 1
        val = m.group(3).strip()
        by_name[m.group(2)].append(dict(file=f, line=ln, value=val))
        v = re.sub(r"[fF]$", "", val)
        if re.fullmatch(r"-?\d+(\.\d+)?(e-?\d+)?", v) and v not in TRIVIAL:
            by_value[v].append(dict(file=f, line=ln, name=m.group(2)))
    if ring_of(f) == "ring1":
        for ln, line in enumerate(src.splitlines(), 1):
            if DEF.search(line): continue
            for lit in re.findall(r"(?<![\w.])(\d+\.\d+)(?![\w.])", line):
                if lit not in TRIVIAL and not lit.endswith(".0"): inline_lit[lit].add(f"{f}:{ln}")
dup_names = {k: v for k, v in by_name.items() if len(set(x["file"] for x in v)) > 1}
dup_values = {k: v for k, v in by_value.items() if len(set(x["name"] for x in v)) > 1 and len(set(x["file"] for x in v)) > 1}
spread_lits = {k: sorted(v) for k, v in inline_lit.items() if len(set(x.split(":")[0] for x in v)) >= 3}
json.dump(dict(dup_names=dup_names, dup_values=dup_values, inline_literals=spread_lits,
               total_constants=sum(len(v) for v in by_name.values())), open(out_path(root, "constants_inventory.json"), "w"), indent=1)
L = ["# Constants inventory (generated by tools/constants_inventory.py — do not edit)", "",
     f"{sum(len(v) for v in by_name.values())} named k-constants in scope.", "",
     f"## Same name defined in more than one file ({len(dup_names)})", "", "| name | definitions (file:line = value) |", "|---|---|"]
for k, v in sorted(dup_names.items(), key=lambda x: -len(x[1])):
    vals = set(x["value"] for x in v)
    L.append(f"| `{k}`{' ⚠ values differ' if len(vals) > 1 else ''} | " + "<br>".join(f"{x['file']}:{x['line']} = {x['value']}" for x in v) + " |")
L += ["", f"## Same distinctive value, different names, different files ({len(dup_values)})", "", "| value | constants |", "|---|---|"]
for k, v in sorted(dup_values.items(), key=lambda x: -len(x[1]))[:80]:
    L.append(f"| {k} | " + "<br>".join(f"`{x['name']}` {x['file']}:{x['line']}" for x in v) + " |")
L += ["", f"## Inline decimal literals repeated in 3+ ring-1 files ({len(spread_lits)})", "", "| literal | sites |", "|---|---|"]
for k, v in sorted(spread_lits.items(), key=lambda x: -len(x[1]))[:60]:
    L.append(f"| {k} | {len(v)}: " + "<br>".join(v[:6]) + (" …" if len(v) > 6 else "") + " |")
open(out_path(root, "constants_inventory.md"), "w").write("\n".join(L) + "\n")
print("constants", sum(len(v) for v in by_name.values()), "dup names", len(dup_names), "dup values", len(dup_values), "spread literals", len(spread_lits))
