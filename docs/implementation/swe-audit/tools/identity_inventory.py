#!/usr/bin/env python3
"""How shots, sessions and athletes are identified, and where one key is translated into another.
   identity_inventory.py <repo-root>

Counts, per file in scope (C++ and QML), the identifiers below, and lists every function whose name says
it TRANSLATES one key into another (…For…/…Of…/rowFor…/indexOf…/…ForSwingDir/…ForIds). The counts are of
names, not of meanings: the audit reads the code to say which numbering each one is.
"""
import os, re, sys, json, collections
sys.path.insert(0, os.path.dirname(__file__))
from common import *

root = sys.argv[1]
KEYS = {
    "shot": ["shotId", "focusedShotId", "selectedShotId", "ordinal", "shotNo", "shotIndex", "swingDir", "focusedSwingDir",
             "selectedSwingDir", "swingId", "shotOrdinal", "dirOf"],
    "session": ["sessionDir", "sessionId", "activeSessionId", "activeSessionDir", "liveSessionDir", "sessionKey", "sessionPath"],
    "athlete": ["athleteDir", "athleteId", "athleteName", "athleteKey", "currentAthlete", "activeAthlete"],
}
files = walk(root, SCOPE + BOUNDARY + ["src/Gui"], CPP_EXT + QML_EXT)
files = sorted(set(files))
counts = {k: collections.Counter() for k in KEYS}
per_file = collections.defaultdict(dict)
translators = []
TR = re.compile(r"\b(\w*(?:IdFor|IdsFor|ForId|ForIds|DirFor|DirsFor|ForSwingDir|ForDir|rowForId|indexOfShot|shotIndexOf|ordinalOf|ordinalFor|dirOf|idOf|shotOf|rowOf)\w*)\s*\(")
DEF = re.compile(r"(?:^|\s)(?:[\w:<>&\*]+\s+)+([\w:]*?(\w*(?:IdFor|IdsFor|ForId|ForIds|DirFor|DirsFor|ForSwingDir|ForDir|rowForId|indexOfShot|ordinalOf|ordinalFor|dirOf|idOf|shotOf))\w*)\s*\([^;]*\)\s*(?:const)?\s*[{:]|function\s+(\w*(?:IdFor|ForId|ForSwingDir|DirFor|dirOf|idOf|ordinalOf)\w*)\s*\(", re.M)
for f in files:
    src = strip_comments(read(root, f)) if f.endswith(CPP_EXT) else read(root, f)
    for kind, names in KEYS.items():
        for nm in names:
            c = len(re.findall(r"\b" + nm + r"\b", src))
            if c: counts[kind][nm] += c; per_file[f][nm] = c
    for m in DEF.finditer(src):
        nm = m.group(1) or m.group(3)
        translators.append(f"{f}:{src[:m.start()].count(chr(10)) + 1}: {nm}")
calls = collections.Counter()
for f in files:
    src = read(root, f)
    for m in TR.finditer(src): calls[m.group(1)] += 1

json.dump(dict(counts={k: dict(v) for k, v in counts.items()}, per_file=per_file, translators=translators,
               translator_calls=dict(calls.most_common())), open(out_path(root, "identity_inventory.json"), "w"), indent=1)
L = ["# Identity inventory (generated by tools/identity_inventory.py — do not edit)", ""]
for kind in KEYS:
    L += [f"## {kind} keys (occurrences across src/Gui + scope)", "", "| name | occurrences | files |", "|---|---|---|"]
    for nm, c in counts[kind].most_common():
        L.append(f"| `{nm}` | {c} | {sum(1 for f in per_file if nm in per_file[f])} |")
    L.append("")
L += [f"## Translator definitions ({len(translators)})", ""] + [f"- {t}" for t in translators]
L += ["", "## Translator calls (by name)", "", "| name | calls |", "|---|---|"] + [f"| `{n}` | {c} |" for n, c in calls.most_common(60)]
open(out_path(root, "identity_inventory.md"), "w").write("\n".join(L) + "\n")
print("files", len(files), "translators", len(translators))
