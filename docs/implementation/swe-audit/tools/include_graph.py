#!/usr/bin/env python3
"""Include graph for the audit scope.   include_graph.py <repo-root>

Writes data/include_graph.json and data/include_graph.md:
  - directory-to-directory include counts (every quoted #include resolved against the including file)
  - edges that run against the ASSUMED layer order below (the order is the audit's working hypothesis,
    stated so a reader can disagree with it, not a rule the code has ever been held to)
  - directory-level and file-level cycles (strongly connected components)
  - per-file fan-in / fan-out inside the scope
"""
import os, re, sys, json, collections
sys.path.insert(0, os.path.dirname(__file__))
from common import *

root = sys.argv[1]
# Assumed order, low to high. Same rank = peers (an edge between peers is reported, not flagged).
RANK = {"Core": 0, "Buffer": 1, "Video": 1, "IMU": 1, "Pose": 1, "Club": 1, "Ball": 1, "Body": 1,
        "Kinematics": 1, "Wrist": 1, "Skeleton3d": 1, "Timeline": 1, "LaunchMonitor": 1, "Audio": 1,
        "Export": 2, "Analysis": 2, "Metrics": 2,
        "Diagnostics": 3, "Coaching": 4, "Gui": 5}
def rank(d):
    head = d.split("/")[0]
    return RANK.get(head)

src_files = walk(root, ["src"], CPP_EXT)
known = set(src_files)
inc_re = re.compile(r'^\s*#\s*include\s+"([^"]+)"', re.M)
edges = collections.defaultdict(set)       # file -> set(file)
unresolved = collections.Counter()
for f in src_files:
    txt = strip_comments(read(root, f)) if False else read(root, f)
    for m in inc_re.finditer(txt):
        target = os.path.normpath(os.path.join(os.path.dirname(f), m.group(1)))
        if target not in known:
            # try src-root relative
            alt = os.path.normpath(os.path.join("src", m.group(1)))
            target = alt if alt in known else None
        if target: edges[f].add(target)
        else: unresolved[m.group(1)] += 1

in_scope = lambda f: ring_of(f) in ("ring1", "ring2", "boundary")
dir_edges = collections.Counter(); examples = collections.defaultdict(list)
for f, ts in edges.items():
    if not in_scope(f): continue
    for t in ts:
        a, b = top_dir(f), top_dir(t)
        if a == b: continue
        dir_edges[(a, b)] += 1
        if len(examples[(a, b)]) < 6: examples[(a, b)].append(f"{f} -> {t}")

against = []
for (a, b), n in sorted(dir_edges.items()):
    ra, rb = rank(a), rank(b)
    if ra is not None and rb is not None and rb > ra:
        against.append(dict(src=a, dst=b, count=n, examples=examples[(a, b)]))

def sccs(nodes, adj):
    idx, low, on, st, out, c = {}, {}, set(), [], [], [0]
    sys.setrecursionlimit(100000)
    def visit(v):
        idx[v] = low[v] = c[0]; c[0] += 1; st.append(v); on.add(v)
        for w in adj.get(v, ()):
            if w not in idx: visit(w); low[v] = min(low[v], low[w])
            elif w in on: low[v] = min(low[v], idx[w])
        if low[v] == idx[v]:
            comp = []
            while True:
                w = st.pop(); on.discard(w); comp.append(w)
                if w == v: break
            if len(comp) > 1: out.append(sorted(comp))
    for v in nodes:
        if v not in idx: visit(v)
    return out

dadj = collections.defaultdict(set)
for (a, b) in dir_edges: dadj[a].add(b)
dir_cycles = sccs(sorted(set(x for e in dir_edges for x in e)), dadj)
fadj = {f: [t for t in ts if in_scope(t)] for f, ts in edges.items() if in_scope(f)}
file_cycles = sccs(sorted(fadj), fadj)

fan_in = collections.Counter()
for f, ts in fadj.items():
    for t in ts: fan_in[t] += 1
fan = sorted(((f, fan_in[f], len(fadj.get(f, []))) for f in set(fadj) | set(fan_in)
              if ring_of(f) in ("ring1", "ring2")), key=lambda x: -(x[1] + x[2]))

json.dump(dict(dir_edges=[dict(src=a, dst=b, count=n) for (a, b), n in sorted(dir_edges.items())],
               against_assumed_order=against, dir_cycles=dir_cycles, file_cycles=file_cycles,
               fan=[dict(file=f, fan_in=i, fan_out=o) for f, i, o in fan],
               unresolved=dict(unresolved.most_common(50))),
          open(out_path(root, "include_graph.json"), "w"), indent=1)

L = ["# Include graph (generated by tools/include_graph.py — do not edit)", "",
     "Assumed layer order, low → high: Core · producers (Buffer, Video, IMU, Pose, Club, Ball, Body, Kinematics, Wrist, Skeleton3d, Timeline, LaunchMonitor, Audio) · Export, Analysis, Metrics · Diagnostics · Coaching · Gui.", "",
     "## Edges against the assumed order", "", "| from | to | includes | examples |", "|---|---|---|---|"]
for e in against:
    L.append(f"| {e['src']} | {e['dst']} | {e['count']} | " + "<br>".join(e["examples"][:3]) + " |")
L += ["", "## Directory cycles", ""] + [("- " + " ↔ ".join(c)) for c in dir_cycles] + ["",
      f"## File-level include cycles in scope ({len(file_cycles)})", ""] + [("- " + ", ".join(c)) for c in file_cycles] + ["",
      "## Directory edges (scope as source)", "", "| from | to | includes |", "|---|---|---|"]
for (a, b), n in sorted(dir_edges.items(), key=lambda x: (x[0][0], -x[1])):
    L.append(f"| {a} | {b} | {n} |")
L += ["", "## Highest fan-in + fan-out (rings 1–2)", "", "| file | fan-in | fan-out |", "|---|---|---|"]
for f, i, o in fan[:40]: L.append(f"| {f} | {i} | {o} |")
open(out_path(root, "include_graph.md"), "w").write("\n".join(L) + "\n")
print("dir edges", len(dir_edges), "against", len(against), "dir cycles", len(dir_cycles), "file cycles", len(file_cycles))
