#!/usr/bin/env python3
"""File sizes, C++ function lengths and inline-function counts.   size_table.py <repo-root>

Function detection is heuristic: a top-level-ish '{' whose preceding text ends in ')' [const|override|noexcept|-> T]
and is not a control statement / lambda / initialiser. Length = lines from the signature's '{' to its matching '}'.
Good enough to rank; the audit reads the code behind anything it cites.
"""
import os, re, sys, json, collections
sys.path.insert(0, os.path.dirname(__file__))
from common import *

root = sys.argv[1]
files = walk(root, SCOPE + BOUNDARY, CPP_EXT)
qml = walk(root, SCOPE, QML_EXT)
CTRL = re.compile(r"\b(if|for|while|switch|catch|return|else|do)\s*$")
SIG_END = re.compile(r"\)(?:\s|const|noexcept|override|final)*$")

funcs, rows = [], []
for f in files:
    raw = read(root, f); src = strip_comments(raw)
    nlines = raw.count("\n") + 1
    inline_n = len(re.findall(r"(?m)^\s*(?:template\s*<[^>]*>\s*)?(?:static\s+)?(?:constexpr\s+)?inline\b(?!\s+constexpr\s+\w+\s*=)(?![^;{(]*=)", src))
    mutable_n = len(re.findall(r"\bmutable\b", src))
    invok_n = len(re.findall(r"\bQ_INVOKABLE\b", src))
    prop_n = len(re.findall(r"\bQ_PROPERTY\b", src))
    # function bodies
    depth, i, n = 0, 0, len(src)
    stack = []
    line_at = [0] * (n + 1); ln = 1
    for k, ch in enumerate(src):
        line_at[k] = ln
        if ch == "\n": ln += 1
    line_at[n] = ln
    while i < n:
        ch = src[i]
        if ch == "{":
            stripped = src[max(0, i - 240):i].rstrip()
            is_fn = False
            if stripped[-1:] in (")", "t", "e", "l") and SIG_END.search(stripped[-60:]) and not any(s[0] for s in stack):
                # walk back to the '(' matching the last ')'
                close = stripped.rfind(")"); d = 0; j = close
                while j >= 0:
                    if stripped[j] == ")": d += 1
                    elif stripped[j] == "(":
                        d -= 1
                        if d == 0: break
                    j -= 1
                tail = stripped[:j].rstrip() if j > 0 else ""
                if tail.endswith("]") or re.search(r"\]\s*$", tail): tail = "if"   # lambda
                if not CTRL.search(tail) and not re.search(r"[=,(]\s*$", tail):
                    m = re.search(r"([~\w:]+)\s*$", tail)
                    if m and m.group(1) not in ("if", "for", "while", "switch", "catch", "return", "sizeof", "decltype", "Q_ASSERT"):
                        is_fn = m.group(1)
            stack.append((is_fn, i))
        elif ch == "}":
            if stack:
                is_fn, start = stack.pop()
                if is_fn and not any(s[0] for s in stack):
                    a, b = line_at[start], line_at[i]
                    funcs.append(dict(file=f, name=is_fn, line=a, length=b - a + 1))
        i += 1
    rows.append(dict(file=f, ring=ring_of(f), lines=nlines, inline_fns=inline_n, mutable=mutable_n,
                     invokables=invok_n, properties=prop_n))
for f in qml:
    raw = read(root, f)
    rows.append(dict(file=f, ring=ring_of(f), lines=raw.count("\n") + 1, inline_fns=0, mutable=0, invokables=0, properties=0))

rows.sort(key=lambda r: -r["lines"]); funcs.sort(key=lambda r: -r["length"])
per_dir = collections.defaultdict(lambda: dict(files=0, cpp_lines=0, qml_lines=0, fns_over_150=0, fns_over_300=0))
for r in rows:
    d = per_dir[top_dir(r["file"])]; d["files"] += 1
    d["qml_lines" if r["file"].endswith(QML_EXT) else "cpp_lines"] += r["lines"]
for fn in funcs:
    d = per_dir[top_dir(fn["file"])]
    if fn["length"] > 150: d["fns_over_150"] += 1
    if fn["length"] > 300: d["fns_over_300"] += 1
json.dump(dict(files=rows, functions=funcs[:600], per_dir=per_dir), open(out_path(root, "size_table.json"), "w"), indent=1)

L = ["# Sizes (generated by tools/size_table.py — do not edit)", "", "## Per directory", "",
     "| dir | files | C++ lines | QML lines | functions > 150 lines | > 300 |", "|---|---|---|---|---|---|"]
for d, v in sorted(per_dir.items(), key=lambda x: -(x[1]["cpp_lines"] + x[1]["qml_lines"])):
    L.append(f"| {d} | {v['files']} | {v['cpp_lines']} | {v['qml_lines']} | {v['fns_over_150']} | {v['fns_over_300']} |")
L += ["", "## Largest files (rings 1–2 + boundary)", "", "| file | lines | inline fns | Q_INVOKABLE | Q_PROPERTY | mutable |", "|---|---|---|---|---|---|"]
for r in rows[:45]:
    L.append(f"| {r['file']} | {r['lines']} | {r['inline_fns']} | {r['invokables']} | {r['properties']} | {r['mutable']} |")
L += ["", "## Longest C++ functions", "", "| function | file:line | lines |", "|---|---|---|"]
for fn in funcs[:60]:
    L.append(f"| `{fn['name']}` | {fn['file']}:{fn['line']} | {fn['length']} |")
open(out_path(root, "size_table.md"), "w").write("\n".join(L) + "\n")
print("files", len(rows), "functions", len(funcs), ">150:", sum(1 for f in funcs if f["length"] > 150), ">300:", sum(1 for f in funcs if f["length"] > 300))
