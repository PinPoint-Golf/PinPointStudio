#!/bin/zsh
# Vendor the launch monitor panel's artwork from the PinPoint Golf Resources repo into the app.
#
#   tools/lm_art/vendor.sh [RESOURCES_DIR]        (default ~/Projects/Resources)
#
# WHAT IT COPIES (docs/design/lm_panel_fsx.md, "Artwork: LmClubArt"):
#   clubheads/out/<club>/<club>_<view>_<look>.png   five heads × top/side/face (+ back for the
#                                                   iron and wedge) × light/dark/line-black/line-white
#   clubheads/out/<club>/<club>_<view>.json         the anchors, VERBATIM — LmClubArt reads them at
#                                                   run time and rescales the pixel fields to the
#                                                   vendored image, so no anchor is ever copied by hand
#   ball/out/ball_side_<look>.png + ball_side.json  the plain ball (side view: the one the spin axis turns)
#   ball/out/dimple-print/patch_<d>mm.svg + .json   the impact patch, 20/25/30 mm, tintable (currentColor)
#   LICENSE                                         MIT — the notice has to travel with the copies
#
# THE SIZE. Every PNG is downscaled with sips to LONG_SIDE px on its long side (the renders are
# 2048). The contract asks for the smallest size at which the Impact face still reaches 3 px/mm
# in physical pixels at Mark's full screen on a 2× display, inside a 15 MB budget. The arithmetic
# is written into VENDORED.md by this script and argued in full there; the short form is that
# the This-shot Impact figure draws a head's face at most ~3 logical px/mm (≈ 6 physical), and
# 1024 px gives every head's face view 5.0–6.4 image px/mm — at or above what the screen shows,
# so the face is never upsampled — while 768 would leave the hybrid and the irons upsampled.
#
# It REPLACES src/Gui/resources/lm/ wholesale (except nothing — there is nothing hand-made in
# there), writes VENDORED.md with the Resources commit, and writes files.cmake, the list the
# app's and qml_ui_test's qt_add_resources read. Re-run it after any Resources change and
# commit the result; nothing is generated at build time.
set -euo pipefail

LONG_SIDE=${LONG_SIDE:-1024}
BALL_SIDE=${BALL_SIDE:-768}     # the Spin figure draws the ball well under 700 physical px across

REPO=${0:A:h:h:h}
RES=${1:-$HOME/Projects/Resources}
DEST=$REPO/src/Gui/resources/lm

[[ -d $RES/clubheads/out && -d $RES/ball/out ]] || { print -u2 "vendor.sh: no Resources checkout at $RES"; exit 1; }
command -v sips >/dev/null || { print -u2 "vendor.sh: needs sips (macOS)"; exit 1; }

COMMIT=$(git -C $RES rev-parse HEAD)
SHORT=$(git -C $RES rev-parse --short HEAD)
SUBJECT=$(git -C $RES log -1 --format=%s)
DIRTY=""
if [[ -n $(git -C $RES status --porcelain -- clubheads/out ball/out LICENSE) ]]; then
    DIRTY=" (WORKING TREE HAD UNCOMMITTED CHANGES under clubheads/out, ball/out or LICENSE)"
    print -u2 "vendor.sh: warning — Resources has uncommitted art; VENDORED.md will say so"
fi

rm -rf $DEST
mkdir -p $DEST/clubheads $DEST/ball

shrink() {   # shrink <src.png> <dst.png> <long side>
    sips -Z $3 $1 --out $2 >/dev/null
}

CLUBS=(driver fairway hybrid iron wedge)
VIEWS=(top side face back)
LOOKS=(light dark line-black line-white)
for club in $CLUBS; do
    mkdir -p $DEST/clubheads/$club
    for view in $VIEWS; do
        json=$RES/clubheads/out/$club/${club}_${view}.json
        [[ -f $json ]] || continue                    # back exists for the iron and wedge only
        cp $json $DEST/clubheads/$club/
        for look in $LOOKS; do
            shrink $RES/clubheads/out/$club/${club}_${view}_${look}.png \
                   $DEST/clubheads/$club/${club}_${view}_${look}.png $LONG_SIDE
        done
    done
done

for look in light dark line-black line-white line-bold-black line-bold-white; do
    shrink $RES/ball/out/ball_side_${look}.png $DEST/ball/ball_side_${look}.png $BALL_SIDE
done
cp $RES/ball/out/ball_side.json $DEST/ball/
for d in 20 25 30; do
    cp $RES/ball/out/dimple-print/patch_${d}mm.svg $RES/ball/out/dimple-print/patch_${d}mm.json $DEST/ball/
done
cp $RES/LICENSE $DEST/LICENSE

# ── files.cmake: the resource list, so CMake never globs ──────────────────────────────
(
    print "# GENERATED by tools/lm_art/vendor.sh — do not edit; re-run the script."
    print "# The launch monitor art, relative to src/Gui/resources/lm/ (Resources $SHORT)."
    print "set(PP_LM_ART_FILES"
    (cd $DEST && find clubheads ball -type f \( -name '*.png' -o -name '*.json' -o -name '*.svg' \) | LC_ALL=C sort) \
        | sed 's/^/    /'
    print ")"
) > $DEST/files.cmake

# ── VENDORED.md ───────────────────────────────────────────────────────────────────────
TOTAL_KB=$(du -sk $DEST | cut -f1)
PNG_KB=$(find $DEST -name '*.png' -exec du -k {} + | awk '{s+=$1} END {print s}')
NFILES=$(cd $DEST && find clubheads ball -type f | wc -l | tr -d ' ')

# The face view's px/mm at the vendored size, per head, from the anchors themselves.
FACE_ROWS=$(/usr/bin/python3 - "$RES" "$LONG_SIDE" <<'PY'
import json, sys
res, side = sys.argv[1], int(sys.argv[2])
for club in ["driver", "fairway", "hybrid", "iron", "wedge"]:
    a = json.load(open(f"{res}/clubheads/out/{club}/{club}_face.json"))
    w, h = a["image"]["width"], a["image"]["height"]
    k = side / max(w, h)
    bb = a["body_bbox"]
    body_mm = (bb[2] - bb[0]) * a["mm_per_px"]
    print(f"| {club} | {w}×{h} → {round(w*k)}×{round(h*k)} | {1/a['mm_per_px']:.2f} | {k/a['mm_per_px']:.2f} | {body_mm:.1f} |")
PY
)

cat > $DEST/VENDORED.md <<EOF
# Vendored launch monitor art

Copied by \`tools/lm_art/vendor.sh\` from the PinPoint Golf **Resources** repository (MIT, see
\`LICENSE\` here), and not edited by hand. Re-run the script to update; do not touch these files.

- **Resources commit:** \`$COMMIT\` — $SUBJECT$DIRTY
- **Vendored:** $(date -u +%Y-%m-%d)
- **Files:** $NFILES ($TOTAL_KB KB in all, of which PNG $PNG_KB KB; budget 15 MB)
- **PNG long side:** heads $LONG_SIDE px, ball $BALL_SIDE px (sources are 2048 px). Anchor JSON is
  copied verbatim; \`LmClubArt::anchors()\` rescales its pixel fields to the vendored image size
  at run time, so the JSON and the PNG can never disagree.

## Why $LONG_SIDE px

The contract: the Impact face must reach ≥ 3 px/mm in physical pixels at Mark's full screen on
a 2× display, at the smallest size that does, inside 15 MB.

At Mark's full screen (2560 logical wide, fontScale 1.35, so em = round(11 × 1.35) = 15 px) a
This-shot club cell is at most 18 em = 270 px tall and 1.9 × 270 = 513 px wide (the mock's
\`clubCellMaxEm\`, \`cellAspectMax\`). The Impact face then spans at most
\`(513 − 2 × 6.8 em − 11) / 1.12 ≈ 266\` logical px across the head's body (\`faceQW\`), which is

| head | body heel–toe | logical px/mm | physical px/mm (2×) |
|---|---|---|---|
| driver  | 121.5 mm | 2.19 | 4.38 |
| 3 wood  | 102.9 mm | 2.59 | 5.17 |
| hybrid  |  89.1 mm | 2.99 | 5.97 |
| 7 iron  |  97.8 mm | 2.72 | 5.44 |
| wedge   |  99.4 mm | 2.68 | 5.35 |

So the screen asks for at most ~6 physical px/mm. The face view at $LONG_SIDE px gives:

| head | image | px/mm at 2048 | px/mm vendored | body mm |
|---|---|---|---|---|
$FACE_ROWS

Every head is at or above what the screen draws (≥ 3 px/mm with room, and never upsampled on
the This-shot figure). 768 px would put the hybrid (4.6) and the irons (4.8) below their screen
density; 1024 is the smallest round size that clears all five. The Session impact map can draw
the face somewhat larger than the This-shot figure and is then upsampled by up to ~1.4×.
EOF

print "vendored $NFILES files from Resources $SHORT into $DEST: ${TOTAL_KB} KB (PNG ${PNG_KB} KB)"
