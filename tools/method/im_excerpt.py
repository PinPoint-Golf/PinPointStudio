#!/usr/bin/env python3
"""im_excerpt.py — prints the information-model excerpt a brief needs, so an agent reads that excerpt and never the
whole of governance/artefacts/information_model.md (about 100k tokens).

  python3 tools/method/im_excerpt.py ID [ID ...] > build/platform/<stage>/IM-<item>.md
  python3 tools/method/im_excerpt.py --im <path> ID [ID ...]     reads another copy of the model (a fixture, a worktree's)
  python3 tools/method/im_excerpt.py --self-test                 proves the rules on a tiny model in a temporary dir

The excerpt is: §10 (ownership) whole, from its "## 10. " heading up to "## 11. "; then, for each id given, every line
that defines it — a table row whose first cell is the id (bold or not), a heading that names it (with its body, up to
the next heading of any level), or a bullet that opens with the id in bold; then the footnote definitions those
defining lines cite. An id matches whole: SHOT-0 does not match SHOT-01. An id with no defining line gets a line saying
so. Without --im it reads governance/artefacts/information_model.md under the current directory, as the old
build/refactor/ copy did, or, when there is none there, the one in the checkout this script lives in.
ctest: im_excerpt_selftest (src/Gui/tests/CMakeLists.txt).
"""
import os
import re
import subprocess
import sys
import tempfile

IM_REL = os.path.join('governance', 'artefacts', 'information_model.md')


def excerpt(lines, ids):
    out = ['# Information-model excerpt (generated by tools/method/im_excerpt.py; read this, not the whole file)', '']
    a = next(i for i, l in enumerate(lines) if l.startswith('## 10. '))
    b = next(i for i in range(a + 1, len(lines)) if lines[i].startswith('## 11. '))
    out += lines[a:b]
    notes = set()
    for id_ in ids:
        pat = re.compile(r'^(\| *\**' + re.escape(id_) + r'\b|#+ .*' + re.escape(id_) + r'\b|- \*\*' + re.escape(id_) + r')')
        rows = [i for i, l in enumerate(lines) if pat.match(l)]
        out += ['', f'## {id_}', '']
        if not rows:
            out.append(f'(no defining row; grep the file for {id_})')
        for i in rows:
            if lines[i].startswith('#'):
                j = i + 1
                while j < len(lines) and not lines[j].startswith('#'):
                    j += 1
                block = lines[i:j]
            else:
                block = [lines[i]]
            out += block
            for l in block:
                notes.update(re.findall(r'\[\^([^\]]+)\]', l))
    out += ['', '## Footnotes cited', '']
    for l in lines:
        m = re.match(r'^\[\^([^\]]+)\]:', l)
        if m and m.group(1) in notes:
            out.append(l)
    return '\n'.join(out)


def default_im():
    if os.path.exists(IM_REL):
        return IM_REL
    return os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', IM_REL)


FIXTURE = """# Information model

## 9. Earlier

| SHOT-01x | a longer id that must not match SHOT-01 | [^c] |

## 10. Ownership

The one rule of ownership.

| Level | Owner |
|---|---|
| shot | Shot |

## 11. Changelog

| 1.9.1 | a changelog row that must stay out |

## 12. Ids

| **SHOT-01** | the shot's id | cites [^a] |

### PREF-02 · a heading id

The body of PREF-02, citing [^b].
A second line of its body.

#### A next heading

Text after the next heading, which must stay out.

[^a]: footnote a.
[^b]: footnote b.
[^c]: footnote c, cited by no defining line.
"""


def self_test():
    fails = []

    def check(cond, what):
        print(('ok   - ' if cond else 'FAIL - ') + what)
        if not cond:
            fails.append(what)

    with tempfile.TemporaryDirectory(prefix='im_excerpt_selftest.') as d:
        im = os.path.join(d, 'information_model.md')
        with open(im, 'w') as f:
            f.write(FIXTURE)
        r = subprocess.run([sys.executable, '-I', os.path.abspath(__file__), '--im', im, 'SHOT-01', 'PREF-02',
                            'SHOT-0', 'ZZZ-99'], capture_output=True, text=True, cwd=d)
        out = r.stdout
        check(r.returncode == 0, 'exit 0 (got %d; stderr: %s)' % (r.returncode, r.stderr.strip()[-200:]))
        check('## 10. Ownership' in out and 'The one rule of ownership.' in out and '| shot | Shot |' in out,
              '§10 is printed whole')
        check('## 11. Changelog' not in out and '| 1.9.1 |' not in out, '§11 onwards is not printed with §10')
        check('| **SHOT-01** | the shot\'s id | cites [^a] |' in out, 'a bold table-row id prints its row')
        check('| SHOT-01x |' not in out, 'an id matches whole (SHOT-01 does not pick up SHOT-01x)')
        check('### PREF-02 · a heading id' in out and 'A second line of its body.' in out,
              'a heading id prints its heading and body')
        check('#### A next heading' not in out and 'which must stay out' not in out,
              'a heading id\'s block stops at the next heading')
        check('[^a]: footnote a.' in out and '[^b]: footnote b.' in out, 'the footnotes the rows cite are printed')
        check('[^c]:' not in out, 'a footnote no defining line cites is not printed')
        check('(no defining row; grep the file for SHOT-0)' in out, 'a prefix of an id is not a match (SHOT-0)')
        check('(no defining row; grep the file for ZZZ-99)' in out, 'an unknown id says it has no defining row')
        check(out.startswith('# Information-model excerpt (generated by tools/method/im_excerpt.py'),
              'the header names the tool\'s new home')
    print('self-test: %s' % ('all cases hold' if not fails else '%d FAILED' % len(fails)))
    return 1 if fails else 0


def main(argv):
    if argv == ['--self-test']:
        return self_test()
    im = None
    if argv[:1] == ['--im']:
        if len(argv) < 2:
            print('usage: im_excerpt.py [--im <path>] ID [ID ...] | --self-test', file=sys.stderr)
            return 2
        im, argv = argv[1], argv[2:]
    if not argv or any(a.startswith('-') for a in argv):
        print('usage: im_excerpt.py [--im <path>] ID [ID ...] | --self-test', file=sys.stderr)
        return 2
    with open(im or default_im()) as f:
        lines = f.read().split('\n')
    print(excerpt(lines, argv))
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
