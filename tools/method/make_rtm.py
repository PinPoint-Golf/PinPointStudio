#!/usr/bin/env python3
"""make_rtm.py: the requirements traceability report, on demand, for release readiness.

    python3 tools/method/make_rtm.py              v1 rows -> build/rtm/rtm.md, issues read live with gh
    python3 tools/method/make_rtm.py --all        every release (v1, v2, later, never)
    python3 tools/method/make_rtm.py --offline    no gh: the bug and issue columns are left out
    python3 tools/method/make_rtm.py --out FILE   write somewhere else

Run it when planning a milestone or preparing a beta or v1 release. It is never a commit gate and nothing it writes
is committed. It reads governance/artefacts/requirements.md, the tests' requirement labels (pp_requirement calls and
`// REQ:` lines in QML tests) and the GitHub issues (through tools/method/requirements_table.py, the same reader as
the growth chart's readiness panel), and writes:

  1. readiness by release and MoSCoW: done out of all, % ready, and how many rows an open bug blocks;
  2. still to do: the v1 Must rows not done or blocked by an open bug (then the v1 Should rows);
  3. the matrix: every row in scope by area, with its status, release, MoSCoW, linked tests, open bugs and other
     open issues. A row with no linked test says so; that is information, not a failure.

A row is done when it is in main, has shipped in a beta and been used for real, with no open blocking bug
(governance/artefacts/requirements.md, "Status values").
"""
import argparse
import datetime as dt
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import requirements_table as rt  # noqa: E402

COLUMNS = ("v1 Must", "v1 Should", "v1 Could", "v2")


def short(text, words=14):
    w = text.replace("*", "").split()
    return " ".join(w[:words]) + (" …" if len(w) > words else "")


def nums(ns):
    return ", ".join(f"#{n}" for n in ns) or "-"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    root = Path(__file__).resolve().parents[2]
    ap.add_argument("--all", action="store_true", help="every release, not only v1")
    ap.add_argument("--offline", action="store_true", help="don't read the issues")
    ap.add_argument("--out", help="the report to write (default build/rtm/rtm.md)")
    args = ap.parse_args()

    rows = rt.read_requirements(root)
    tests = rt.read_test_labels(root)
    issues = None if args.offline else rt.read_issues()
    if issues is None and not args.offline:
        print("issues left out: gh issue list failed", file=sys.stderr)
    rt.link_issues(rows, issues)
    head = subprocess.run(["git", "-C", str(root), "rev-parse", "--short", "HEAD"], capture_output=True,
                          text=True).stdout.strip() or "unknown"
    scope = rows if args.all else [r for r in rows if r["release"] == "v1"]
    have_bugs = issues is not None

    out = [f"# Requirements traceability, {dt.date.today():%-d %b %Y}, main {head}", ""]
    out.append(f"{len(rows)} requirements in `governance/artefacts/requirements.md`; this report shows "
               f"{'every release' if args.all else 'v1'}. Generated by `tools/method/make_rtm.py`; not committed."
               + ("" if have_bugs else " **Issues not read** (offline or gh failed): no bug or issue columns."))
    out += ["", "## Readiness", "", "| | Rows | Done | Partial | Planned | Proposed | % ready |"
            + (" Blocked by an open bug |" if have_bugs else ""),
            "|---|---|---|---|---|---|---|" + ("---|" if have_bugs else "")]
    for col in COLUMNS:
        cr = [r for r in rows if rt.column(r) == col and r["status"] != "won't have"]
        if not cr:
            continue
        cnt = {s: sum(r["status"] == s for r in cr) for s in rt.STATUSES}
        ready = sum(r["status"] == "done" and not r.get("open_bugs") for r in cr)
        line = (f"| {col} | {len(cr)} | {cnt['done']} | {cnt['partial']} | {cnt['planned']} | {cnt['proposed']} "
                f"| {100 * ready / len(cr):.0f}% |")
        if have_bugs:
            line += f" {sum(bool(r['open_bugs']) for r in cr)} |"
        out.append(line)
    out += ["", "% ready counts done rows with no open bug.", ""]

    for col in ("v1 Must", "v1 Should"):
        todo = [r for r in rows if rt.column(r) == col and r["status"] != "won't have"
                and (r["status"] != "done" or r.get("open_bugs"))]
        out += [f"## Still to do: {col} ({len(todo)})", ""]
        if not todo:
            out += ["Nothing.", ""]
            continue
        out += ["| Id | Area | Requirement | Status | Open bugs | Other open issues |", "|---|---|---|---|---|---|"]
        for r in todo:
            out.append(f"| {r['id']} | {r['area']} | {short(r['text'])} | {r['raw_status']} | "
                       f"{nums(r.get('open_bugs', [])) if have_bugs else '?'} | "
                       f"{nums(r.get('open_other', [])) if have_bugs else '?'} |")
        out.append("")

    out += ["## The matrix", ""]
    for area in dict.fromkeys(r["area"] for r in scope):
        ar = [r for r in scope if r["area"] == area]
        out += [f"### {area}", "", "| Id | Requirement | Release | MoSCoW | Status | Tests"
                + (" | Open bugs | Other open issues |" if have_bugs else " |"),
                "|---|---|---|---|---|---|" + ("---|---|" if have_bugs else "")]
        for r in ar:
            t = tests.get(r["id"], [])
            line = (f"| {r['id']} | {short(r['text'])} | {r['release']} | {r['moscow'] or '-'} | {r['raw_status']} "
                    f"| {', '.join(f'`{x}`' for x in t) if t else 'no linked test'} |")
            if have_bugs:
                line += f" {nums(r['open_bugs'])} | {nums(r['open_other'])} |"
            out.append(line)
        out.append("")

    unknown = sorted(set(tests) - {r["id"] for r in rows})
    if unknown:
        out += ["## Labels naming no live requirement", "",
                ", ".join(f"{k} ({', '.join(tests[k])})" for k in unknown), ""]

    dest = Path(args.out) if args.out else root / "build/rtm/rtm.md"
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text("\n".join(out), encoding="utf-8")
    print(dest)


if __name__ == "__main__":
    main()
