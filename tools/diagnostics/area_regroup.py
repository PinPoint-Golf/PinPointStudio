#!/usr/bin/env python3
"""The condition area regroup, driven by area_regroup_map.json.

The map (condition id -> { new, old } group token) is the one source. This script:

  * rewrites the "group" value of each condition in core.json, by text, so every other byte of the
    file stays as authored;
  * generates src/Diagnostics/packs/area_regroup_table.h, the compiled copy of the map that the pack
    loader's alias step reads.

Usage:
    area_regroup.py            rewrite core.json and the header
    area_regroup.py --check    exit 1 when the header and the map disagree; touches nothing

Stops with a report, changing nothing, if a condition in core.json is missing from the map, or if an
id appears twice in either file. --check compares only the header and the map, so conditions added to
core.json after the regroup do not fail it: they were never renamed, and need no alias.
"""

