# A condition's own "id" and "group" sit at exactly this indent; anything nested sits deeper.
ROW_ID = re.compile(r'^      "id": "([^"]+)",?\r?$')
ROW_GROUP = re.compile(r'^(      "group": ")([^"]+)(",?\r?)$')


def stop(lines):
    print("area_regroup: STOPPED, nothing changed.", file=sys.stderr)
    for line in lines:
        print("  " + line, file=sys.stderr)
    sys.exit(2)


def no_duplicate_keys(pairs):
    keys = [k for k, _ in pairs]
    repeated = sorted({k for k in keys if keys.count(k) > 1})
    if repeated:
        stop(["appears twice in the map: " + k for k in repeated])
    return dict(pairs)


def read_map():
    with MAP.open(encoding="utf-8") as f:
        table = json.load(f, object_pairs_hook=no_duplicate_keys)
    bad = [k for k, v in table.items() if set(v) != {"new", "old"}]
    if bad:
        stop(["map row is not { new, old }: " + k for k in bad])
    return table


def render_header(table):
    rows = "\n".join(
        '    {{ "{}", "{}", "{}" }},'.format(i, table[i]["new"], table[i]["old"]) for i in sorted(table)
    )
    return (
        LICENCE
        + """
#pragma once

// GENERATED by tools/diagnostics/area_regroup.py from tools/diagnostics/area_regroup_map.json.
// Do not edit by hand. `area_regroup.py --check` fails when this file and the map disagree.
//
// Every condition that existed when the swing areas were regrouped, with the group token it moved
// from and the one it moved to. The pack loader reads it to bring forward a file written before the
// regroup; see currentConditionGroupToken() in characteristic_pack.h.

namespace pinpoint::analysis::detail {

struct AreaRegroupRow {
    const char *id;
    const char *newToken;
    const char *oldToken;
};

inline constexpr AreaRegroupRow kAreaRegroupTable[] = {
"""
        + rows
        + """
};

} // namespace pinpoint::analysis::detail
"""
    )


def rewrite_core(table):
    with CORE.open(encoding="utf-8", newline="") as f:
        text = f.read()
    parsed = json.loads(text)
    ids = [c["id"] for c in parsed["conditions"]]
    problems = ["missing from the map: " + i for i in ids if i not in table]
    problems += ["appears twice in core.json: " + i for i in sorted({i for i in ids if ids.count(i) > 1})]
    if problems:
        stop(problems)

    for c in parsed["conditions"]:
        row = table[c["id"]]
        if c["group"] not in (row["old"], row["new"]):
            problems.append(
                "{} holds group {}, the map expects {} or {}".format(c["id"], c["group"], row["old"], row["new"])
            )
    if problems:
        stop(problems)

    lines = text.split("\n")
    start = next(n for n, l in enumerate(lines) if l.startswith('  "conditions": ['))
    end = next(n for n in range(start, len(lines)) if lines[n].startswith("  ]"))
    current = None
    seen = []
    for n in range(start, end):
        m = ROW_ID.match(lines[n])
        if m:
            current = m.group(1)
            continue
        m = ROW_GROUP.match(lines[n])
        if m:
            if current is None:
                stop(["a group line with no id before it, at line {}".format(n + 1)])
            lines[n] = m.group(1) + table[current]["new"] + m.group(3)
            seen.append(current)
            current = None
    if sorted(seen) != sorted(ids):
        stop(["rewrote {} group lines for {} conditions".format(len(seen), len(ids))])

    updated = "\n".join(lines)
    check = json.loads(updated)
    for c in check["conditions"]:
        if c["group"] != table[c["id"]]["new"]:
            stop([c["id"] + " did not take its new group"])
    with CORE.open("w", encoding="utf-8", newline="") as f:
        f.write(updated)
    print("area_regroup: core.json: {} group values written".format(len(seen)))


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="exit 1 when the header and the map disagree")
    args = parser.parse_args()

    table = read_map()
    wanted = render_header(table)
    if args.check:
        current = HEADER.read_text(encoding="utf-8") if HEADER.exists() else ""
        if current != wanted:
            print("area_regroup: {} is stale against the map".format(HEADER.relative_to(ROOT)), file=sys.stderr)
            sys.exit(1)
        print("area_regroup: header matches the map ({} rows)".format(len(table)))
        return

    rewrite_core(table)
    HEADER.write_text(wanted, encoding="utf-8")
    print("area_regroup: wrote {}".format(HEADER.relative_to(ROOT)))


if __name__ == "__main__":
    main()
